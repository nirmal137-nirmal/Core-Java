package in.co.corejava.oop.Inheritance;

public class Bike extends Vehicle{
	
	private int engineCC;
	private String discBrake;
	private String helmetType;
	
	
	public int getEngineCC() {
		return engineCC;
	}
	public void setEngineCC(int engineCC) {
		this.engineCC = engineCC;
	}
	public String getDiscBrake() {
		return discBrake;
	}
	public void setDiscBrake(String discBrake) {
		this.discBrake = discBrake;
	}
	public String getHelmetType() {
		return helmetType;
	}
	public void setHelmetType(String helmetType) {
		this.helmetType = helmetType;
	}
	
	

}
