package in.co.corejava.practice;

public class TestPrintTable {

	public static void main(String[] args) {

		for (int i = 1; i <= 10; i++) {
			System.out.print(i * 1 + "\t");
		}

		System.out.println();
		System.out.println();

		for (int i = 1; i <= 10; i++) {
			System.out.print(i * 2 + "\t");
		}

		System.out.println();
		System.out.println();

		for (int i = 1; i <= 10; i++) {
			System.out.print(i * 3 + "\t");
		}

		System.out.println();
		System.out.println();

	}
}
