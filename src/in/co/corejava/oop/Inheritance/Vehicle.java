package in.co.corejava.oop.Inheritance;

public class Vehicle {
	
	protected String vihicleName;
	protected String vihicleNumber;
	protected String fueltype;
	protected double price;
	protected String color;
	
	
	public String getVihicleName() {
		return vihicleName;
	}
	public void setVihicleName(String vihicleName) {
		this.vihicleName = vihicleName;
	}
	public String getVihicleNumber() {
		return vihicleNumber;
	}
	public void setVihicleNumber(String vihicleNumber) {
		this.vihicleNumber = vihicleNumber;
	}
	public String getFueltype() {
		return fueltype;
	}
	public void setFueltype(String fueltype) {
		this.fueltype = fueltype;
	}
	public double getPrice() {
		return price;
	}
	public void setPrice(double price) {
		this.price = price;
	}
	public String getColor() {
		return color;
	}
	public void setColor(String color) {
		this.color = color;
	}
	
	
	
	
	
	

}
